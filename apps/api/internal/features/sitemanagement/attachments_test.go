func TestValidateManualEvidence_rejectsShortUnicodeInput(t *testing.T) {
	// Given a statement with fewer than twenty Unicode code points.
	statement := strings.Repeat("证", ManualEvidenceMinRunes-1)

	// When the manual evidence is parsed.
	_, err := validateManualEvidence(statement)

	// Then the boundary rejects it before a claim can be stored.
	require.Error(t, err)
	var serviceErr *ServiceError
	require.ErrorAs(t, err, &serviceErr)
	require.Equal(t, "invalid_evidence", serviceErr.Code)
}

func TestValidateAttachmentContent_acceptsPDFOnlyWithMagicAndDeclaredType(t *testing.T) {
	// Given a PDF-sized byte stream with a valid header.
	content := append([]byte("%PDF-1.7\n"), bytes.Repeat([]byte("x"), 128)...)
	input := AttachmentUploadInput{Filename: "proof.pdf", ContentType: "application/pdf", Size: int64(len(content))}

	// When the completion boundary validates the upload.
	err := ValidateAttachmentContent(input, content)

	// Then the PDF is accepted.
	require.NoError(t, err)
}

func TestValidateAttachmentContent_rejectsPDFWithImageTypeOrHeader(t *testing.T) {
	// Given a PDF filename with a mismatched media type and then a bad header.
	content := []byte("%PDF-1.7\nbody")
	wrongType := AttachmentUploadInput{Filename: "proof.pdf", ContentType: "application/octet-stream", Size: int64(len(content))}
	wrongHeader := AttachmentUploadInput{Filename: "proof.pdf", ContentType: "application/pdf", Size: int64(len(content))}

	// When each invalid upload reaches completion.
	errType := ValidateAttachmentContent(wrongType, content)
	errHeader := ValidateAttachmentContent(wrongHeader, []byte("not a pdf"))

	// Then both are rejected at the boundary.
	require.Error(t, errType)
	require.Error(t, errHeader)
}

func TestValidateAttachmentContent_enforcesImageLimitAndFormat(t *testing.T) {
	// Given a valid PNG and JPEG generated by the standard library.
	imageData := image.NewRGBA(image.Rect(0, 0, 2, 2))
	imageData.Set(0, 0, color.RGBA{R: 255, A: 255})
	var pngBytes bytes.Buffer
	require.NoError(t, png.Encode(&pngBytes, imageData))
	var jpegBytes bytes.Buffer
	require.NoError(t, jpeg.Encode(&jpegBytes, imageData, nil))

	// When both declared formats are checked against their content.
	errPNG := ValidateAttachmentContent(AttachmentUploadInput{Filename: "proof.png", ContentType: "image/png", Size: int64(pngBytes.Len())}, pngBytes.Bytes())
	errJPEG := ValidateAttachmentContent(AttachmentUploadInput{Filename: "proof.jpg", ContentType: "image/jpeg", Size: int64(jpegBytes.Len())}, jpegBytes.Bytes())

	// Then valid images pass; a size over five MiB fails before decode.
	require.NoError(t, errPNG)
	require.NoError(t, errJPEG)
	require.Error(t, AttachmentUploadInput{Filename: "proof.png", ContentType: "image/png", Size: ManualImageMaxBytes + 1}.Validate())
}

func TestAttachmentUploadInput_rejectsUnsafeFilenames(t *testing.T) {
	for _, filename := range []string{"../proof.pdf", `..\\proof.pdf`, strings.Repeat("p", 256) + ".pdf"} {
		input := AttachmentUploadInput{Filename: filename, ContentType: "application/pdf", Size: 5}
		require.Error(t, input.Validate(), filename)
	}
}

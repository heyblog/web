    primary_parent_required: '请选择有效的一级分类。',
    source_unavailable: '来源标签已不可用，请刷新后重新选择。',
    secondary_required: '只有二级分类可以调整所属一级分类。',
    target_path_missing: '目标标签缺少对应分类路径，请先完善分类。',
